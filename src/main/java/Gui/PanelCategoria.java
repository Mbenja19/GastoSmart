    public void actualizar() {
        modelo.setRowCount(0);
        for (Categoria c : usuario.getCategorias()) {
            modelo.addRow(new Object[] { c.getNombre(),
                    c.isEsencial() ? "esencial" : "no esencial",
                    c.isActiva() ? "activa" : "inactiva",
                    String.format("%.2f", c.getMontoReservado()) });
        }
    }

    private void agregar() {
        JTextField txtNombre = new JTextField(15);
        JCheckBox chkEsencial = new JCheckBox("Es una necesidad (esencial)");
        JTextField txtReservado = new JTextField("0", 10);
        Double[] reservado = new Double[1];

        boolean ok = Util.pedirDatos(this, "Agregar categoría",
                new Object[] { "Nombre de la categoría:", txtNombre, chkEsencial,
                        "Monto que quieres reservar para ella (S/):", txtReservado },
                () -> {
                    String nombre = txtNombre.getText().trim();
                    if (nombre.isEmpty()) {
                        Util.error(this, "El nombre no puede estar vacío.");
                        return false;
                    }
                    for (Categoria c : usuario.getCategorias()) {
                        if (c.getNombre().equalsIgnoreCase(nombre)) {
                            Util.error(this, "Esa categoría ya existe.");
                            return false;
                        }
                    }
                    reservado[0] = Util.leerMonto(this, txtReservado.getText(), "Monto reservado", true);
                    return reservado[0] != null;
                });
        if (!ok) {
            return;
        }
        usuario.agregarCategoria(new Categoria(txtNombre.getText().trim(), chkEsencial.isSelected(), reservado[0]));
        alCambiar.run();
    }

    private void cambiarEstado() {
        int fila = tabla.getSelectedRow();
        if (fila < 0) {
            Util.error(this, "Primero selecciona una categoría de la tabla.");
            return;
        }
        Categoria c = usuario.getCategorias().get(fila);
        if (c.isActiva()) {
            c.desactivar();
        } else {
            c.activar();
        }
        alCambiar.run();
    }

