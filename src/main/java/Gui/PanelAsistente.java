    private void evaluar() {
        String articulo = txtArticulo.getText().trim();
        if (articulo.isEmpty()) {
            Util.error(this, "Escribe qué quieres comprar.");
            return;
        }
        Double precio = Util.leerMonto(this, txtPrecio.getText(), "Precio", false);
        if (precio == null) {
            return;
        }

        String resultado = usuario.evaluar(precio);
        double libre = usuario.calcularDineroLibre();

        StringBuilder sb = new StringBuilder();
        sb.append("Quieres comprar: ").append(articulo).append("\n");
        sb.append(String.format("Precio: S/ %.2f%n", precio));
        sb.append(String.format("Tu saldo actual: S/ %.2f%n", usuario.getSaldoActual()));
        sb.append(String.format("Dinero libre: S/ %.2f (lo que queda sin tocar tus necesidades)%n%n", libre));

        Color color;
        switch (resultado) {
            case "VIABLE":
                color = new Color(0, 130, 0);
                sb.append(String.format("Después de comprarlo te quedarían S/ %.2f libres.", libre - precio));
                break;
            case "VIABLE CON RIESGO":
                color = new Color(210, 120, 0);
                sb.append(String.format(
                        "Puedes pagarlo, pero usarías más del %.0f%% de tu dinero libre. Te quedarían S/ %.2f.",
                        Usuario.LIMITE_RIESGO * 100, libre - precio));
                break;
            default:
                color = new Color(190, 0, 0);
                sb.append(String.format(
                        "Te faltan S/ %.2f de dinero libre para comprarlo sin descuidar tus necesidades.",
                        precio - libre));
        }
        sb.append("\n\nConsejo: ").append(Consejos.consejoAleatorio());

        lblResultado.setText(resultado);
        lblResultado.setForeground(color);
        txtDetalle.setText(sb.toString());
    }
