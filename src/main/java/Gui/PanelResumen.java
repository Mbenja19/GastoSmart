    public void actualizar() {
        PresupuestoMensual p = usuario.getPresupuesto();
        lblSaldo.setText(String.format("Saldo actual: S/ %.2f", usuario.calcularSaldo()));
        lblLibre.setText(String.format("Dinero libre (sin tocar tus necesidades): S/ %.2f",
                usuario.calcularDineroLibre()));

        if (p.getMontoMaximo() > 0) {
            double gastado = p.calcularTotalGastos(usuario.getTransacciones());
            double restante = p.calcularRestante(usuario.getTransacciones());
            lblPresupuesto.setText(String.format("Presupuesto del mes: S/ %.2f", p.getMontoMaximo()));
            lblGastado.setText(String.format("Gastado en el presupuesto: S/ %.2f", gastado));
            lblRestante.setText(restante >= 0
                    ? String.format("Te queda del presupuesto: S/ %.2f", restante)
                    : String.format("¡Superaste el presupuesto por S/ %.2f!", Math.abs(restante)));
            int porcentaje = (int) Math.round(gastado / p.getMontoMaximo() * 100);
            barra.setValue(Math.min(porcentaje, 100));
            barra.setString("Presupuesto usado: " + porcentaje + "%");
            barra.setVisible(true);
        } else {
            lblPresupuesto.setText("Presupuesto del mes: sin presupuesto");
            lblGastado.setText(" ");
            lblRestante.setText(" ");
            barra.setVisible(false);
        }
    }
    
    private void cambiarPresupuesto() {
        PresupuestoMensual p = usuario.getPresupuesto();
        JTextField txt = new JTextField(String.format("%.2f", p.getMontoMaximo()));
        Double[] valor = new Double[1];

        boolean ok = Util.pedirDatos(this, "Cambiar presupuesto",
                new Object[] { "Nuevo presupuesto máximo (0 = sin presupuesto):", txt },
                () -> {
                    valor[0] = Util.leerMonto(this, txt.getText(), "Presupuesto", true);
                    return valor[0] != null;
                });
        if (!ok) {
            return;
        }

        p.modificarMonto(valor[0]);
        double yaGastado = p.calcularTotalGastos(usuario.getTransacciones());
        if (valor[0] > 0 && yaGastado > 0) {
            int r = JOptionPane.showConfirmDialog(this,
                    String.format("Este mes ya gastaste S/ %.2f.%n¿Empezar el nuevo presupuesto de cero "
                            + "(sin contar lo ya gastado)?", yaGastado),
                    "Cambiar presupuesto", JOptionPane.YES_NO_OPTION);
            if (r == JOptionPane.YES_OPTION) {
                p.iniciarDeCero(usuario.getTransacciones());
            }
        }
        alCambiar.run();
    }
    
    
    

