    public VentanaPrincipal(Usuario usuario) {
        initComponents();
        
        this.usuario = usuario;
        setTitle("GastoSmart - " + usuario.getNombre());
        setLocationRelativeTo(null); // Centra la ventana en pantalla

        // Inicializas tus paneles existentes igual que antes
        resumen = new PanelResumen(usuario, this::refrescar);
        movimientos = new PanelMovimientos(usuario, this::refrescar);
        categorias = new PanelCategoria(usuario, this::refrescar);
        metas = new PanelMetas(usuario, this::refrescar);
        asistente = new PanelAsistente(usuario);

        // Agregas tus paneles como pestañas al JTabbedPane visual
        pestanas.addTab("Resumen", resumen);
        pestanas.addTab("Movimientos", movimientos);
        pestanas.addTab("Categorías", categorias);
        pestanas.addTab("Metas de ahorro", metas);
        pestanas.addTab("Asistente de compra", asistente);

        refrescar();
    }
    
    public void refrescar() {
    lblSaldo.setText(String.format("Hola, %s   |   Saldo actual: S/ %.2f",
            usuario.getNombre(), usuario.calcularSaldo()));
    resumen.actualizar();
    movimientos.actualizar();
    categorias.actualizar();
    metas.actualizar();
}


