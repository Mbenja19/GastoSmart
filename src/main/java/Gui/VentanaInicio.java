    private void comenzar() {
        String nombre = txtNombre.getText().trim();
        String correo = txtCorreo.getText().trim();

        if (!Util.esNombreValido(nombre)) {
            Util.error(this, "El nombre es obligatorio y solo puede tener letras y espacios.");
            return;
        }
        if (!Util.esCorreoValido(correo)) {
            Util.error(this, "Correo no válido. Ejemplo: nombre@correo.com");
            return;
        }
        Double dinero = Util.leerMonto(this, txtDinero.getText(), "Dinero inicial", true);
        if (dinero == null) {
            return;
        }
        Double presupuesto = Util.leerMonto(this, txtPresupuesto.getText(), "Presupuesto", true);
        if (presupuesto == null) {
            return;
        }

        Usuario usuario = new Usuario(nombre, correo);
        usuario.setDineroInicial(dinero);
        usuario.getPresupuesto().modificarMonto(presupuesto);

        dispose();
        new VentanaPrincipal(usuario).setVisible(true);
    }
    

